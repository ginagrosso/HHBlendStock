// ─── Generador de ticket ────────────────────────────────────────────────────────
// Simula la respuesta del endpoint POST /caja/finalizar-venta.
// El backend debe generar el número de ticket real con secuencia persistente.
let _contadorTicket = 1

export function generarTicketMock(
  items: ItemCarrito[],
  metodoPago: MetodoPago,
  cliente?: DatosCliente,
): Ticket {
  const numero = `TKT-${String(_contadorTicket++).padStart(5, '0')}`

  const lineas: LineaTicket[] = items.map((item) => {
    const precioUnitario =
      metodoPago === 'tarjeta' ? item.precioTarjeta : item.precioEfectivo
    return {
      descripcion: item.nombre,
      articulo: item.articulo,
      talle: item.talle,
      cantidad: item.cantidad,
      precioUnitario,
      subtotal: precioUnitario * item.cantidad,
    }
  })

  const total = lineas.reduce((acc, l) => acc + l.subtotal, 0)

  return {
    numero,
    fecha: new Date().toISOString(),
    metodoPago,
    lineas,
    total,
    cliente,
  }
}
